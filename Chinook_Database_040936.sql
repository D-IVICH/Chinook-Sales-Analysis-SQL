--TASK 10:RANKING ACCORDING TO REVENUE
--Rank products(tracks) according to the revenue they generated
SELECT T.TrackId,
		T.Name,
		SUM(IL.UnitPrice*IL.Quantity) AS Total_Revenue,
		RANK() OVER(
		ORDER BY 
	SUM(IL.UnitPrice*IL.Quantity)DESC) AS Revenue_Rank
FROM Track AS T
INNER JOIN InvoiceLine AS IL
	ON T.TrackId = IL.TrackId
GROUP BY T.TrackId,
		T.Name
ORDER BY Revenue_Rank ASC,
		 T.TrackId ASC
LIMIT 10