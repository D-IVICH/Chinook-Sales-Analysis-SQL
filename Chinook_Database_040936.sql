--TASK 8:MONTHLY SALES PERFORMANCE
--1. Revenue generated by each month in each year
--We use the Invoice Table as it contains the date of each invoice, the total amount for each and id for each unique id
SELECT TO_CHAR(DATE_TRUNC('month',InvoiceDate),'YYYY-MM') AS Sales_Month,
		COUNT(InvoiceId) AS Total_Invoice,
		ROUND(SUM(Total),2) AS Monthly_Revenue
FROM Invoice
GROUP BY DATE_TRUNC('month',InvoiceDate)
ORDER BY Sales_Month

--2.Highest Revenue month
SELECT TO_CHAR(DATE_TRUNC('month',InvoiceDate),'YYYY-MM') AS Sales_Month,
		COUNT(InvoiceId) AS Total_Invoice,
		ROUND(SUM(Total),2) AS Monthly_Revenue
FROM Invoice
GROUP BY DATE_TRUNC('month',InvoiceDate)
ORDER BY Monthly_Revenue DESC
LIMIT 1

--3.Lowest Revenue month
SELECT TO_CHAR(DATE_TRUNC('month',InvoiceDate),'YYYY-MM') AS Sales_Month,
		COUNT(InvoiceId) AS Total_Invoice,
		ROUND(SUM(Total),2) AS Monthly_Revenue
FROM Invoice
GROUP BY DATE_TRUNC('month',InvoiceDate)
ORDER BY Monthly_Revenue ASC
LIMIT 1

--TASK 9:PRODUCT PERFORMANCE BY QUANTITY
--1. Identify the Top 10 Best-Selling Products
--Which tracks have sold the highest number of units?
SELECT T.Name,
		T.TrackId,
		SUM(IL.Quantity) AS Units_Sold
FROM Track AS T
INNER JOIN InvoiceLine AS IL
	ON T.TrackId = IL.TrackId
GROUP BY T.Name,
	T.TrackId
ORDER BY Units_Sold DESC
