--TASK 3: BUSINESS ANALYSIS
--1. Overall Sales Performance
--Get the Total Revenue generated by Chinook Digital Music Store(From InvoiceLine Table)
SELECT SUM(UnitPrice*Quantity) AS Total_Revenue
FROM InvoiceLine

--Calculate total revenue(from Invoice Table), total invoices, and average invoice value
SELECT SUM(Total) AS Total_Revenue,
		COUNT(InvoiceId) AS Total_Invoice,
		ROUND(AVG(Total),2) AS Average_Invoice_Value
FROM Invoice

--2. Revenue Analysis by Country
--(The Total column in Invoice Table is the Revenue generated by each Invoice)
--Calculate total revenue for each country, with the highest-revenue country appearing first
SELECT Customer.Country,
		SUM(Invoice.Total) AS Total_Revenue
FROM Customer
INNER JOIN Invoice 
	ON Customer.CustomerId = Invoice.CustomerId
GROUP BY Customer.Country
ORDER BY Total_Revenue DESC

--Identify the Top 5 countries that generated the highest revenue
SELECT Customer.Country,
		SUM(Invoice.Total) AS Total_Revenue
FROM Customer
INNER JOIN Invoice 
	ON Customer.CustomerId = Invoice.CustomerId
GROUP BY Customer.Country
ORDER BY Total_Revenue DESC
LIMIT 5


--TASK 4:CUSTOMER PURCHASING ANALYSIS
--Identify Top 5 Customers by Spending, result should contain CustomerId, First Name, Last Name and Total amount spent
SELECT C.CustomerId,
		C.FirstName,
		C.LastName,
		SUM(I.Total) AS Total_Amount_Spent
FROM Customer AS C
INNER JOIN Invoice AS I
	ON C.CustomerId = I.CustomerId
GROUP BY C.CustomerId,
		C.FirstName,
		C.LastName
ORDER BY Total_Amount_Spent DESC
LIMIT 5


--TASK 5:PRODUCT PERFORMANCE ANALYSIS
--Top 10 music tracks that generated the highest revenue
--This should include the track id, track name and total revenue generated by each track and sort in descending order of magnitude
SELECT T.TrackId,
		T.Name,
		SUM(IL.UnitPrice*IL.Quantity) AS Total_Revenue
FROM Track AS T
INNER JOIN InvoiceLine AS IL
	ON T.TrackId = IL.TrackId
GROUP BY T.TrackId,
		T.Name
ORDER BY Total_Revenue DESC
LIMIT 10

